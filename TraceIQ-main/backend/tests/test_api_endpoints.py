"""API integration tests using FastAPI TestClient with lifespan context.
"""

import pytest
from fastapi.testclient import TestClient
from bugdiag.main import app
from bugdiag.database.session import init_db

@pytest.fixture(autouse=True)
def setup_test_database():
    init_db()

def test_root_endpoint():
    with TestClient(app) as client:
        response = client.get("/")
        assert response.status_code == 200
        data = response.json()
        assert "TraceIQ" in data["message"]

def test_health_endpoint():
    with TestClient(app) as client:
        response = client.get("/api/v1/health")
        assert response.status_code == 200
        data = response.json()
        assert "status" in data
        assert "database" in data
        assert "embeddings" in data

def test_system_architecture_endpoint():
    with TestClient(app) as client:
        response = client.get("/api/v1/system/architecture")
        assert response.status_code == 200
        data = response.json()
        assert len(data["agents"]) == 5
        agent_names = [a["name"] for a in data["agents"]]
        assert "Triage Agent" in agent_names
        assert "Log Analysis Agent" in agent_names
        assert "Root Cause Agent" in agent_names
        assert "Duplicate Detection Agent" in agent_names
        assert "Remediation Agent" in agent_names

def test_bug_submission_and_diagnosis_workflow():
    with TestClient(app) as client:
        payload = {
            "title": "NullPointerException in payment gateway callback",
            "description": "During webhook callback processing, null pointer was thrown when looking up customer billing profile without verified address.",
            "stack_trace": "java.lang.NullPointerException at com.app.billing.PaymentCallback.process(PaymentCallback.java:94)",
            "programming_language": "Java",
            "framework": "Spring Boot",
            "severity": "high",
            "priority": "p1",
            "reproduction_steps": "Send mock stripe webhook event with missing customer address object."
        }

        # 1. Create bug submission
        response = client.post("/api/v1/submissions", json=payload)
        assert response.status_code == 201
        created_bug = response.json()
        bug_id = created_bug["id"]
        assert bug_id is not None
        assert created_bug["title"] == payload["title"]

        # 2. Retrieve submission details
        details_res = client.get(f"/api/v1/submissions/{bug_id}")
        assert details_res.status_code == 200

        # 3. Explicitly trigger the documented pipeline after submission/attachments.
        trigger_res = client.post(
            "/api/v1/diagnosis/trigger",
            json={"submission_id": bug_id, "force_reanalysis": False},
        )
        assert trigger_res.status_code == 200
        assert trigger_res.json()["status"] == "completed"

        # 4. Retrieve the persisted diagnosis report generated by the 5-Agent pipeline.
        diag_res = client.get(f"/api/v1/diagnosis/{bug_id}")
        assert diag_res.status_code == 200
        diag_report = diag_res.json()

        assert diag_report["triage_result"] is not None
        assert diag_report["triage_result"]["category"] == "NullPointer"
        assert diag_report["log_analysis_result"] is not None
        assert diag_report["log_analysis_result"]["has_stack_trace"] is True
        assert diag_report["root_cause_result"] is not None
        assert diag_report["remediation_result"] is not None
        assert diag_report["duplicate_detection_result"] is not None
        assert diag_report["overall_confidence"] > 0.0

        # 5. Check persisted agent execution logs
        logs_res = client.get(f"/api/v1/diagnosis/{bug_id}/logs")
        assert logs_res.status_code == 200
        logs = logs_res.json()
        assert len(logs) >= 5

import React, { useState, useEffect } from 'react';
import { useParams, Link } from 'react-router-dom';
import {
  Sparkles,
  ArrowLeft,
  RefreshCw,
  Copy,
  Check,
  Download,
  Share2,
  ExternalLink,
  ShieldCheck,
  Terminal,
  Activity,
  GitBranch,
  Cpu,
  Layers,
  ChevronDown,
  ChevronUp,
  FileCode,
  AlertTriangle,
  CheckCircle2,
  Clock
} from 'lucide-react';
import { IOSBadge } from '../components/ios/IOSBadge';
import { IOSSegmentedControl } from '../components/ios/IOSSegmentedControl';
import { LoadingSkeleton } from '../components/ui/LoadingSkeleton';
import { ToastItem, ToastMessage } from '../components/ui/Toast';
import { api } from '../services/api';
import { BugSubmission, DiagnosisReport, AgentExecutionLog } from '../types';

export const SubmissionDetailsPage: React.FC = () => {
  const { id } = useParams<{ id: string }>();
  const [submission, setSubmission] = useState<BugSubmission | null>(null);
  const [report, setReport] = useState<DiagnosisReport | null>(null);
  const [logs, setLogs] = useState<AgentExecutionLog[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [isReanalyzing, setIsReanalyzing] = useState(false);
  const [copiedPatch, setCopiedPatch] = useState(false);
  const [toasts, setToasts] = useState<ToastMessage[]>([]);
  const [activeTab, setActiveTab] = useState<'diagnosis' | 'duplicates' | 'forensics' | 'agents'>('diagnosis');

  const addToast = (type: 'success' | 'error' | 'info', title: string, message?: string) => {
    setToasts((prev) => [...prev, { id: Math.random().toString(), type, title, message }]);
  };

  const removeToast = (id: string) => {
    setToasts((prev) => prev.filter((t) => t.id !== id));
  };

  const loadData = async () => {
    if (!id) return;
    setIsLoading(true);
    try {
      const [subData, reportData, logsData] = await Promise.all([
        api.getSubmissionById(id),
        api.getDiagnosisReport(id).catch(() => null),
        api.getExecutionLogs(id).catch(() => []),
      ]);
      setSubmission(subData);
      setReport(reportData);
      setLogs(logsData);
    } catch (err) {
      console.error('Failed to load submission details:', err);
    } finally {
      setIsLoading(false);
      setIsReanalyzing(false);
    }
  };

  useEffect(() => {
    loadData();
  }, [id]);

  const handleReanalyze = async () => {
    if (!id) return;
    setIsReanalyzing(true);
    try {
      addToast('info', 'Re-evaluating Swarm', 'Running the backend diagnosis pipeline with the current knowledge base...');
      const updatedReport = await api.triggerDiagnosis(id, true);
      setReport(updatedReport);
      const updatedLogs = await api.getExecutionLogs(id);
      setLogs(updatedLogs);
      addToast('success', 'Analysis Completed', 'Diagnosis report refreshed.');
    } catch (err: any) {
      addToast('error', 'Analysis Failed', err.message || 'Failed to complete analysis.');
    } finally {
      setIsReanalyzing(false);
    }
  };

  const handleCopyPatch = (patchText: string) => {
    navigator.clipboard.writeText(patchText);
    setCopiedPatch(true);
    addToast('success', 'Code Patch Copied', 'Diff snippet copied to your clipboard.');
    setTimeout(() => setCopiedPatch(false), 2000);
  };

  const handleExportMarkdown = () => {
    if (!submission || !report) return;
    const md = `# TraceIQ Defect Diagnosis Report
**Report ID:** ${submission.id}
**Date:** ${new Date().toISOString()}
**Title:** ${submission.title}
**Severity:** ${submission.severity} | **Priority:** ${submission.priority}
**Language:** ${submission.programming_language} | **Framework:** ${submission.framework || 'N/A'}

---

## 1. Executive Summary & Root Cause
**Identified Cause:** ${report.root_cause_result?.identified_root_cause}
**Evidence Score (not a probability):** ${(report.root_cause_result?.confidence || 0) * 100}%
**Explanation:** ${report.root_cause_result?.explanation}

---

## 2. Duplicate Detection
**Duplicate Match:** ${report.duplicate_detection_result?.is_duplicate ? 'Yes' : 'No'}
**Highest Similarity:** ${((report.duplicate_detection_result?.highest_similarity || 0) * 100).toFixed(1)}%
${report.duplicate_detection_result?.potential_duplicates?.map((d) => `- ${d.defect_id} (${d.source_repo}): ${d.title} [Score: ${d.similarity_score}]`).join('\n')}

---

## 3. Recommended Remediation & Code Patch
${[...(report.remediation_result?.verified_fixes || []), ...(report.remediation_result?.suggested_fixes || [])].map((f) => `### ${f.title}\n${f.description}${f.diff_snippet ? `\n\`\`\`diff\n${f.diff_snippet}\n\`\`\`` : ''}`).join('\n\n')}

Note: historical resolution notes and suggested actions are not automatically verified code patches.

---
*Generated by TraceIQ — Intelligent Bug Diagnosis Platform (Milestone 1 Foundation + M2 Agents)*`;

    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `TraceIQ-Report-${submission.id.substring(0, 8)}.md`;
    a.click();
    URL.revokeObjectURL(url);
    addToast('success', 'Report Exported', 'Markdown diagnosis document downloaded.');
  };

  if (isLoading) {
    return (
      <div className="max-w-6xl mx-auto space-y-6 py-6">
        <LoadingSkeleton rows={10} />
      </div>
    );
  }

  if (!submission) {
    return (
      <div className="max-w-2xl mx-auto my-12 p-8 text-center ios-card">
        <h2 className="text-lg font-bold text-slate-900 dark:text-white">Defect Submission Not Found</h2>
        <p className="text-xs text-slate-500 mt-2 mb-4">The requested ID does not exist or was deleted.</p>
        <Link
          to="/reports"
          className="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-blue-500 text-white text-xs font-semibold"
        >
          <ArrowLeft className="w-4 h-4" />
          <span>Back to Bug Reports</span>
        </Link>
      </div>
    );
  }

  const triage = report?.triage_result;
  const logAnalysis = report?.log_analysis_result;
  const rootCause = report?.root_cause_result;
  const duplicate = report?.duplicate_detection_result;
  const remediation = report?.remediation_result;

  return (
    <div className="max-w-6xl mx-auto space-y-6 pb-16">
      {/* Toast notifications */}
      <div className="fixed top-20 right-6 z-50 space-y-2 pointer-events-none">
        {toasts.map((toast) => (
          <div key={toast.id} className="pointer-events-auto">
            <ToastItem toast={toast} onClose={() => removeToast(toast.id)} />
          </div>
        ))}
      </div>

      {/* Top Header & Breadcrumb */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div className="space-y-1">
          <div className="flex items-center gap-2 text-xs text-slate-500 dark:text-zinc-400">
            <Link to="/reports" className="hover:text-blue-500 flex items-center gap-1">
              <ArrowLeft className="w-3.5 h-3.5" />
              <span>Bug Reports</span>
            </Link>
            <span>/</span>
            <span className="font-mono text-slate-700 dark:text-zinc-300">{submission.id}</span>
          </div>
          <h1 className="text-xl sm:text-2xl font-bold tracking-tight text-slate-900 dark:text-white">
            {submission.title}
          </h1>
        </div>

        {/* Action Buttons */}
        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={handleExportMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-xl bg-black/5 dark:bg-white/5 hover:bg-black/10 dark:hover:bg-white/10 text-xs font-medium text-slate-700 dark:text-zinc-300 border border-black/5 dark:border-white/5 transition-all"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Export Report</span>
          </button>

          <button
            type="button"
            onClick={handleReanalyze}
            disabled={isReanalyzing}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-[#007AFF] hover:bg-[#0066D6] dark:bg-[#0A84FF] text-white text-xs font-semibold shadow-sm transition-all disabled:opacity-50"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isReanalyzing ? 'animate-spin' : ''}`} />
            <span>Re-run Agents</span>
          </button>

          <IOSBadge
            variant={
              submission.severity === 'critical' ? 'red' : submission.severity === 'high' ? 'orange' : 'blue'
            }
            size="sm"
          >
            {submission.severity.toUpperCase()}
          </IOSBadge>
        </div>
      </div>

      {/* Hero Diagnostic Card */}
      <div className="rounded-3xl p-6 sm:p-8 bg-gradient-to-br from-[#0F172A] via-[#090D16] to-[#030712] text-white shadow-2xl border border-white/10 relative overflow-hidden">
        <div className="relative z-10 flex flex-col md:flex-row md:items-center justify-between gap-6">
          <div className="space-y-3">
            <div className="flex items-center gap-2">
              <span className="w-8 h-8 rounded-xl bg-blue-500/20 text-blue-400 flex items-center justify-center">
                <Sparkles className="w-4 h-4" />
              </span>
              <span className="text-xs font-bold uppercase tracking-wider text-blue-400">
                TraceIQ Structured Findings
              </span>
              <span className="text-[11px] text-zinc-400">
                • {report ? new Date(report.updated_at).toLocaleString() : 'Analyzing'}
              </span>
            </div>

            <h2 className="text-lg sm:text-xl font-bold tracking-tight text-white max-w-3xl">
              {rootCause?.identified_root_cause || 'Synthesizing root cause hypotheses across 5 agents...'}
            </h2>

            <p className="text-xs sm:text-sm text-zinc-300 max-w-3xl leading-relaxed">
              {rootCause?.explanation || submission.description}
            </p>
          </div>

          {/* Metric Gauge */}
          <div className="flex-shrink-0 flex items-center gap-4 bg-white/5 p-4 rounded-2xl border border-white/10">
            <div className="text-center">
              <div className="text-2xl font-extrabold text-cyan-400 font-mono">
                {rootCause ? `${Math.round(rootCause.confidence * 100)}%` : '—'}
              </div>
              <div className="text-[10px] text-zinc-400 uppercase font-semibold">Evidence Score</div>
              <div className="text-[9px] text-zinc-500">Not a probability</div>
            </div>
            <div className="w-px h-10 bg-white/10" />
            <div className="text-center">
              <div className="text-2xl font-extrabold text-blue-400 font-mono">
                {duplicate ? `${Math.round(duplicate.highest_similarity * 100)}%` : '—'}
              </div>
              <div className="text-[10px] text-zinc-400 uppercase font-semibold">Top Relevance</div>
            </div>
          </div>
        </div>
      </div>

      {/* iOS Segmented View Switcher */}
      <div className="flex justify-center sm:justify-start">
        <IOSSegmentedControl
          value={activeTab}
          onChange={(v) => setActiveTab(v as any)}
          options={[
            { value: 'diagnosis', label: 'Executive Diagnosis', icon: <Sparkles className="w-3.5 h-3.5" /> },
            {
              value: 'duplicates',
              label: 'Historical Duplicates',
              icon: <GitBranch className="w-3.5 h-3.5" />,
              badge: duplicate?.potential_duplicates?.length || 0,
            },
            { value: 'forensics', label: 'Stack Forensics', icon: <Terminal className="w-3.5 h-3.5" /> },
            { value: 'agents', label: 'Agent Execution Trace', icon: <Layers className="w-3.5 h-3.5" /> },
          ]}
        />
      </div>

      {/* Tab 1: Executive Diagnosis */}
      {activeTab === 'diagnosis' && (
        <div className="space-y-6">
          {/* Triage & Metadata Pill Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
            <div className="ios-card p-4 space-y-1">
              <span className="text-[11px] font-semibold text-slate-500 dark:text-zinc-400">Category</span>
              <div className="font-semibold text-xs sm:text-sm text-slate-900 dark:text-white">
                {triage?.category || 'Not available'}
              </div>
            </div>

            <div className="ios-card p-4 space-y-1">
              <span className="text-[11px] font-semibold text-slate-500 dark:text-zinc-400">Target Subsystem</span>
              <div className="font-semibold text-xs sm:text-sm text-slate-900 dark:text-white">
                {triage?.framework || submission.framework || 'Not identified'}
              </div>
            </div>

            <div className="ios-card p-4 space-y-1">
              <span className="text-[11px] font-semibold text-slate-500 dark:text-zinc-400">Language</span>
              <div className="font-semibold text-xs sm:text-sm text-slate-900 dark:text-white">
                {triage?.programming_language || submission.programming_language || 'Not identified'}
              </div>
            </div>

            <div className="ios-card p-4 space-y-1">
              <span className="text-[11px] font-semibold text-slate-500 dark:text-zinc-400">Report Completeness</span>
              <div className="font-semibold text-xs sm:text-sm text-emerald-500">
                {triage ? `${Math.round(triage.completeness_score * 100)}% (${triage.completeness_score >= 0.8 ? 'Good' : triage.completeness_score >= 0.5 ? 'Partial' : 'Incomplete'})` : 'Not available'}
              </div>
            </div>
          </div>

          {/* Remediation & Actionable Patches */}
          <div className="ios-card p-6 space-y-6">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-black/5 dark:border-white/5 pb-4">
              <div>
                <h3 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
                  <ShieldCheck className="w-5 h-5 text-emerald-500" />
                  <span>Remediation Agent: Grounded Fix Recommendation</span>
                </h3>
                <p className="text-xs text-slate-500 dark:text-zinc-400 mt-0.5">
                  Historical notes are references only; suggested fixes must be reviewed and tested.
                </p>
              </div>

              {remediation?.historical_references?.[0] && (
                <a
                  href={remediation.historical_references[0].url || '#'}
                  target="_blank"
                  rel="noreferrer"
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-blue-500/10 hover:bg-blue-500/20 text-blue-600 dark:text-blue-400 text-xs font-medium self-start sm:self-auto"
                >
                  <span>Cited: {remediation.historical_references[0].defect_id}</span>
                  <ExternalLink className="w-3.5 h-3.5" />
                </a>
              )}
            </div>

            {/* Historical fixes that were independently verified (none are claimed by the current pipeline). */}
            {remediation?.verified_fixes?.map((fix, idx) => (
              <div key={idx} className="space-y-3">
                <div className="flex items-center justify-between">
                  <div>
                    <h4 className="font-semibold text-sm text-slate-900 dark:text-white">
                      {fix.title}
                    </h4>
                    <p className="text-xs text-slate-600 dark:text-zinc-300 mt-1">
                      {fix.description}
                    </p>
                  </div>
                  <IOSBadge variant="green" size="sm">
                    Verified Fix
                  </IOSBadge>
                </div>

                {/* Diff Viewer */}
                {fix.diff_snippet && (
                  <div className="relative rounded-2xl bg-[#090D16] border border-white/10 p-4 text-xs font-mono text-zinc-300 overflow-x-auto">
                    <button
                      type="button"
                      onClick={() => handleCopyPatch(fix.diff_snippet!)}
                      className="absolute top-3 right-3 flex items-center gap-1 px-2.5 py-1 rounded-lg bg-white/10 hover:bg-white/20 text-xs text-zinc-200 transition-all"
                    >
                      {copiedPatch ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                      <span>{copiedPatch ? 'Copied' : 'Copy Patch'}</span>
                    </button>
                    <pre className="text-[11px] leading-relaxed pt-2">
                      {fix.diff_snippet}
                    </pre>
                  </div>
                )}
              </div>
            ))}

            {/* Suggestions and historical notes are shown as unverified guidance. */}
            {remediation?.suggested_fixes?.map((fix, idx) => (
              <div key={`suggested-${idx}`} className="rounded-2xl border border-amber-500/20 bg-amber-500/5 p-4 space-y-2">
                <div className="flex items-center justify-between gap-3">
                  <h4 className="font-semibold text-sm text-slate-900 dark:text-white">{fix.title}</h4>
                  <IOSBadge variant="orange" size="sm">Review before use</IOSBadge>
                </div>
                <p className="text-xs text-slate-600 dark:text-zinc-300 leading-relaxed">{fix.description}</p>
              </div>
            ))}

            {/* Rationale */}
            {remediation?.rationale && (
              <div className="p-4 rounded-2xl bg-black/5 dark:bg-white/5 border border-black/5 dark:border-white/5 text-xs text-slate-700 dark:text-zinc-300 leading-relaxed">
                <span className="font-semibold text-slate-900 dark:text-white">Architectural Rationale: </span>
                {remediation.rationale}
              </div>
            )}
          </div>

          {/* Supporting Evidence Breakdown */}
          {rootCause?.supporting_evidence && rootCause.supporting_evidence.length > 0 && (
            <div className="ios-card p-6 space-y-4">
              <h3 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
                <CheckCircle2 className="w-4 h-4 text-blue-500" />
                <span>Supporting Technical Evidence</span>
              </h3>
              <div className="space-y-2">
                {rootCause.supporting_evidence.map((ev, i) => (
                  <div
                    key={i}
                    className="p-3 rounded-xl bg-black/5 dark:bg-white/5 border border-black/5 dark:border-white/5 text-xs text-slate-700 dark:text-zinc-300 flex items-start gap-2.5"
                  >
                    <span className="w-1.5 h-1.5 rounded-full bg-blue-500 mt-1.5 flex-shrink-0" />
                    <span>{ev}</span>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}

      {/* Tab 2: Historical Duplicates */}
      {activeTab === 'duplicates' && (
        <div className="space-y-6">
          <div className="ios-card p-6 space-y-4">
            <div className="border-b border-black/5 dark:border-white/5 pb-3">
              <h3 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
                <GitBranch className="w-5 h-5 text-purple-500" />
                <span>Duplicate Candidate Rankings (RRF Hybrid Search)</span>
              </h3>
              <p className="text-xs text-slate-500 dark:text-zinc-400 mt-0.5">
                Matched against the historical records currently loaded in this TraceIQ knowledge base. Scores are relevance indicators, not probabilities.
              </p>
            </div>

            {duplicate?.potential_duplicates && duplicate.potential_duplicates.length > 0 ? (
              <div className="space-y-3">
                {duplicate.potential_duplicates.map((dup, i) => (
                  <div
                    key={i}
                    className="p-5 rounded-2xl bg-black/5 dark:bg-white/5 border border-black/5 dark:border-white/5 space-y-3 hover:border-purple-500/30 transition-all"
                  >
                    <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                      <div className="flex items-center gap-2">
                        <span className="font-mono font-bold text-sm text-purple-600 dark:text-purple-400">
                          {dup.defect_id}
                        </span>
                        <span className="text-xs text-zinc-400">({dup.source_repo})</span>
                      </div>
                      <IOSBadge variant="purple" size="sm">
                        {Math.round(dup.similarity_score * 100)}% Similarity
                      </IOSBadge>
                    </div>

                    <h4 className="font-semibold text-sm text-slate-900 dark:text-white">
                      {dup.title}
                    </h4>

                    <div className="text-[11px] text-zinc-400 font-mono">
                      Retrieval Mode: {dup.retrieval_method}
                    </div>
                  </div>
                ))}
              </div>
            ) : (
              <div className="py-8 text-center text-xs text-zinc-400">
                No possible duplicate crossed the configured relevance threshold. Similarity scores are relevance indicators, not probabilities.
              </div>
            )}
          </div>
        </div>
      )}

      {/* Tab 3: Stack Forensics */}
      {activeTab === 'forensics' && (
        <div className="space-y-6">
          <div className="ios-card p-6 space-y-5">
            <div className="border-b border-black/5 dark:border-white/5 pb-3 flex items-center justify-between">
              <div>
                <h3 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
                  <Terminal className="w-5 h-5 text-cyan-500" />
                  <span>Log Analysis Agent: Parsed Stack Frames</span>
                </h3>
                <p className="text-xs text-slate-500 dark:text-zinc-400 mt-0.5">
                  Normalized memory addresses and file references for cross-version tracking.
                </p>
              </div>

              {logAnalysis?.exception_type && (
                <IOSBadge variant="red" size="sm">
                  {logAnalysis.exception_type}
                </IOSBadge>
              )}
            </div>

            {/* Frame List */}
            {logAnalysis?.stack_frames && logAnalysis.stack_frames.length > 0 ? (
              <div className="space-y-2">
                {logAnalysis.stack_frames.map((frame, idx) => (
                  <div
                    key={idx}
                    className="p-3 rounded-xl bg-black/5 dark:bg-white/5 border border-black/5 dark:border-white/5 font-mono text-xs flex flex-col sm:flex-row sm:items-center justify-between gap-1 text-slate-800 dark:text-zinc-200"
                  >
                    <div className="flex items-center gap-2">
                      <span className="text-blue-500 font-bold">#{idx}</span>
                      <span className="font-semibold text-slate-900 dark:text-white">{frame.function || 'unknown'}</span>
                    </div>
                    <div className="text-zinc-400 text-[11px]">
                      {frame.file}{frame.line ? `:${frame.line}` : ''}
                    </div>
                  </div>
                ))}
              </div>
            ) : (
              <div className="p-4 rounded-2xl bg-[#0B0F19] border border-white/10 font-mono text-xs text-zinc-300">
                <pre>{submission.stack_trace || 'No stack trace provided'}</pre>
              </div>
            )}

            {/* Offending Files */}
            {logAnalysis?.suspect_files && (
              <div className="space-y-2 pt-2">
                <span className="text-xs font-semibold text-slate-700 dark:text-zinc-300">
                  Suspect Offending Source Files:
                </span>
                <div className="flex flex-wrap gap-2">
                  {logAnalysis.suspect_files.map((file, i) => (
                    <span
                      key={i}
                      className="px-2.5 py-1 rounded-lg bg-blue-500/10 text-blue-600 dark:text-blue-400 font-mono text-xs border border-blue-500/20"
                    >
                      {file}
                    </span>
                  ))}
                </div>
              </div>
            )}
          </div>
        </div>
      )}

      {/* Tab 4: Agent Execution Logs */}
      {activeTab === 'agents' && (
        <div className="space-y-6">
          <div className="ios-card p-6 space-y-4">
            <div className="border-b border-black/5 dark:border-white/5 pb-3">
              <h3 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
                <Layers className="w-5 h-5 text-blue-500" />
                <span>Agent Execution Trace</span>
              </h3>
              <p className="text-xs text-slate-500 dark:text-zinc-400 mt-0.5">
                Deterministic agent execution timeline and latency telemetry.
              </p>
            </div>

            <div className="space-y-3">
              {logs.map((log) => (
                <div
                  key={log.id}
                  className="p-4 rounded-2xl bg-black/5 dark:bg-white/5 border border-black/5 dark:border-white/5 space-y-2"
                >
                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-2">
                      <span className="w-2 h-2 rounded-full bg-emerald-400" />
                      <span className="font-semibold text-xs sm:text-sm text-slate-900 dark:text-white">
                        {log.agent_name}
                      </span>
                    </div>
                    <span className="text-xs font-mono text-zinc-400">
                      {log.execution_time_ms} ms
                    </span>
                  </div>

                  {log.output_payload && (
                    <div className="p-3 rounded-xl bg-[#090D16] border border-white/10 font-mono text-[11px] text-zinc-300 overflow-x-auto">
                      <pre>{JSON.stringify(log.output_payload, null, 2)}</pre>
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
